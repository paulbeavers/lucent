# its named ones, so redefining @theme_bg_color would change next to nothing:
# these are explicit rules instead, for what Thunar draws.
#
# Thunar's main window carries the style class "thunar", so its rules are
# scoped to it and nothing else's window changes. Menus, popovers and tooltips
# are windows of their own with no such class, so those few rules reach every
# GTK 3 app — consistently, which is the point.
#
# The rules go in lucent.css, and gtk.css only gets an @import of it, added
# once at the top: a gtk.css of your own is never overwritten. GTK 3 reads the
